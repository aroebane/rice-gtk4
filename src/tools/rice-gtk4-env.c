/* Writes rice-gtk4.env: the two variables a consumer sets so GTK 4 finds the rice theme, or writes
 * nothing. rice-gtk4-env [--config FILE] [--themes DIR] [--out FILE|-] GTK 4 looks a theme up in
 * $XDG_DATA_HOME/themes, ~/.themes, then each $XDG_DATA_DIRS entry + /themes, so the directory to
 * export is the parent of themes/. SPDX-License-Identifier: GPL-3.0-or-later */
#include <glib/gstdio.h>
#include <stdio.h>
#include <string.h>

#include "../core/theme.h"

static int usage(void)
{
    fputs(
        "Usage: rice-gtk4-env [--config FILE] [--themes DIR] [--out FILE|-]\n"
        "  --config  Config file (default: $RICE_GTK4_CONFIG or ~/.config/rice/gtk4.conf).\n"
        "  --themes  Themes directory written by rice-gtk4-css (default: themes/ beside the "
        "config).\n"
        "  --out     Env file to write (default: rice-gtk4.env beside the config; - for stdout).\n",
        stderr);
    return 2;
}

int main(int argc, char **argv)
{
    const char *config = NULL, *themes = NULL, *out = NULL;
    for (int i = 1; i < argc; ++i) {
        if ((!strcmp(argv[i], "--config") || !strcmp(argv[i], "-c")) && i + 1 < argc)
            config = argv[++i];
        else if (!strcmp(argv[i], "--themes") && i + 1 < argc)
            themes = argv[++i];
        else if ((!strcmp(argv[i], "--out") || !strcmp(argv[i], "-o")) && i + 1 < argc)
            out = argv[++i];
        else
            return usage();
    }
    r4_theme *t = r4_theme_load(config);
    char *cfgdir = g_path_get_dirname(t->config_path);
    char *root =
        themes ? g_canonicalize_filename(themes, NULL) : g_build_filename(cfgdir, "themes", NULL);
    char *css = g_build_filename(root, "rice", "gtk-4.0", "gtk.css", NULL);
    int status = 1;
    if (!g_file_test(css, G_FILE_TEST_IS_REGULAR)) {
        fprintf(stderr,
                "rice-gtk4-env: %s is missing: run rice-gtk4-css first\nrice-gtk4-env: nothing "
                "written\n",
                css);
    } else if (!g_path_is_absolute(root) || strcmp(g_path_get_basename(root), "themes") != 0) {
        fprintf(stderr,
                "rice-gtk4-env: %s must be an absolute path ending in /themes (GTK looks in "
                "DIR/themes)\nrice-gtk4-env: nothing written\n",
                root);
    } else {
        char *data = g_path_get_dirname(root);
        char *body = g_strdup_printf("# Generated by rice-gtk4-env from %s. Do not "
                                     "edit.\nXDG_DATA_DIRS=%s\nGTK_THEME=rice\n",
                                     t->config_path,
                                     data);
        if (out && !strcmp(out, "-")) {
            fputs(body, stdout);
            status = 0;
        } else {
            char *dest = out ? g_strdup(out) : g_build_filename(cfgdir, "rice-gtk4.env", NULL);
            char *tmp = g_strconcat(dest, ".tmp", NULL);
            GError *err = NULL;
            if (!g_file_set_contents(tmp, body, -1, &err)) {
                fprintf(stderr, "rice-gtk4-env: cannot write %s: %s\n", dest, err->message);
                g_error_free(err);
            } else if (g_rename(tmp, dest) != 0) {
                fprintf(stderr, "rice-gtk4-env: cannot write %s\n", dest);
                g_unlink(tmp);
            } else {
                status = 0;
            }
            g_free(tmp);
            g_free(dest);
        }
        g_free(body);
        g_free(data);
    }
    g_free(css);
    g_free(root);
    g_free(cfgdir);
    r4_theme_free(t);
    return status;
}
