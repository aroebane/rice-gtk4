/* Writes the GTK 4 theme directory, or writes nothing.
 * rice-gtk4-css [--config FILE] [--out DIR] [--settings FILE] [--fidelity | --dump-design]
 * Layout: DIR/rice/index.theme, DIR/rice/gtk-4.0/gtk.css, DIR/rice/gtk-4.0/gtk-dark.css
 * SPDX-License-Identifier: GPL-3.0-or-later */
#include <glib/gstdio.h>
#include <stdio.h>
#include <string.h>

#include "../core/css.h"

static int usage(void)
{
    fputs(
        "Usage: rice-gtk4-css [--config FILE] [--out DIR] [--settings FILE] [--fidelity | "
        "--dump-design]\n"
        "  --fidelity     Print what the design asks for and what GTK 4 CSS draws; write nothing.\n"
        "  --dump-design  Print the resolved design, sorted, for diffing; write nothing.\n"
        "  --settings  Also write a GTK settings.ini: theme name, dark preference from the mode, "
        "font and icons.\n"
        "  --config  Config file (default: $RICE_GTK4_CONFIG or ~/.config/rice/gtk4.conf).\n"
        "  --out     Themes directory (default: themes/ beside the config). The theme is "
        "DIR/rice.\n",
        stderr);
    return 2;
}

/* Temp name beside the target, then rename, so a reader never sees half a file. */
static gboolean put(const char *dest, const char *body)
{
    char *tmp = g_strconcat(dest, ".tmp", NULL);
    GError *err = NULL;
    gboolean ok = g_file_set_contents(tmp, body, -1, &err);
    if (!ok) {
        fprintf(stderr, "rice-gtk4-css: cannot write %s: %s\n", dest, err->message);
        g_error_free(err);
    } else if (g_rename(tmp, dest) != 0) {
        fprintf(stderr, "rice-gtk4-css: cannot write %s\n", dest);
        g_unlink(tmp);
        ok = FALSE;
    }
    g_free(tmp);
    return ok;
}

int main(int argc, char **argv)
{
    const char *config = NULL, *out = NULL, *settings = NULL;
    gboolean fidelity = FALSE, dump = FALSE;
    for (int i = 1; i < argc; ++i) {
        if ((!strcmp(argv[i], "--config") || !strcmp(argv[i], "-c")) && i + 1 < argc)
            config = argv[++i];
        else if ((!strcmp(argv[i], "--out") || !strcmp(argv[i], "-o")) && i + 1 < argc)
            out = argv[++i];
        else if (!strcmp(argv[i], "--fidelity"))
            fidelity = TRUE;
        else if (!strcmp(argv[i], "--dump-design"))
            dump = TRUE;
        else if (!strcmp(argv[i], "--settings") && i + 1 < argc)
            settings = argv[++i];
        else
            return usage();
    }
    r4_theme *t = r4_theme_load(config);
    if (g_getenv("RICE_GTK4_DEBUG") || t->problems->len) {
        for (guint i = 0; i < t->problems->len; ++i)
            fprintf(stderr,
                    "rice-gtk4-css: %s: %s\n",
                    t->config_path,
                    (char *)g_ptr_array_index(t->problems, i));
        for (guint i = 0; i < t->unknown->len; ++i)
            fprintf(stderr,
                    "rice-gtk4-css: %s: unknown key %s\n",
                    t->config_path,
                    (char *)g_ptr_array_index(t->unknown, i));
    }
    /* The contrast guard is never silent: each raised or failing role is printed. */
    for (guint i = 0; i < t->corrections->len; ++i)
        fprintf(
            stderr, "rice-gtk4-css: contrast: %s\n", (char *)g_ptr_array_index(t->corrections, i));
    GError *err = NULL;
    char *css = r4_css_render(t, &err);
    if (!css) {
        fprintf(stderr, "rice-gtk4-css: %s\n", err->message);
        g_error_free(err);
        r4_theme_free(t);
        return 1;
    }
    if (fidelity || dump) {
        /* The report comes after the render: clamps and downgrades are found while rendering. */
        char *rep = dump ? r4_design_dump(&t->design, &t->shape)
                         : r4_design_fidelity(&t->design, &t->shape, &t->diag);
        fputs(rep, stdout);
        g_free(rep);
        g_free(css);
        r4_theme_free(t);
        return 0;
    }
    char *cfgdir = g_path_get_dirname(t->config_path);
    char *root = out ? g_strdup(out) : g_build_filename(cfgdir, "themes", NULL);
    char *gtkdir = g_build_filename(root, "rice", "gtk-4.0", NULL);
    int status = 1;
    if (g_mkdir_with_parents(gtkdir, 0755) != 0) {
        fprintf(stderr, "rice-gtk4-css: cannot create %s\n", gtkdir);
    } else {
        char *idx = r4_index_theme(t);
        char *p_idx = g_build_filename(root, "rice", "index.theme", NULL);
        char *p_css = g_build_filename(gtkdir, "gtk.css", NULL);
        char *p_dark = g_build_filename(gtkdir, "gtk-dark.css", NULL);
        /* One palette, so one stylesheet: GTK_THEME=rice:dark and the dark-preference setting both
         * land here. */
        status = (put(p_idx, idx) && put(p_css, css) && put(p_dark, css)) ? 0 : 1;
        if (status == 0 && settings) {
            GString *st = g_string_new(
                "# Generated by rice-gtk4-css. Do not edit.\n[Settings]\ngtk-theme-name=rice\n");
            g_string_append_printf(st, "gtk-application-prefer-dark-theme=%d\n", t->dark ? 1 : 0);
            if (t->font_general)
                g_string_append_printf(st, "gtk-font-name=%s\n", t->font_general);
            if (t->icon_theme)
                g_string_append_printf(st, "gtk-icon-theme-name=%s\n", t->icon_theme);
            char *sdir = g_path_get_dirname(settings);
            g_mkdir_with_parents(sdir, 0755);
            status = put(settings, st->str) ? 0 : 1;
            g_free(sdir);
            g_string_free(st, TRUE);
        }
        g_free(idx);
        g_free(p_idx);
        g_free(p_css);
        g_free(p_dark);
    }
    g_free(gtkdir);
    g_free(root);
    g_free(cfgdir);
    g_free(css);
    r4_theme_free(t);
    return status;
}
