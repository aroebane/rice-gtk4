#!/usr/bin/env python3
"""Writes the element manifest ids and hooks as a C table: elements.py element-hooks.yaml out.c.

The manifest is authoritative (ids, hooks); nothing is invented here. Top-level ids and parts
both appear, in file order. Every `hooks:` line is a one-line flow list."""
import re
import sys

ident = re.compile(r"^\s*(?:- )?id:\s*(\S+)\s*$")
hooks = re.compile(r"^\s*hooks:\s*\[(.*)\]\s*$")
quoted = re.compile(r'"((?:[^"\\]|\\.)*)"')

rows, cur = [], None
for line in open(sys.argv[1], encoding="utf-8"):
    m = ident.match(line)
    if m:
        cur = m.group(1)
        continue
    m = hooks.match(line)
    if m and cur:
        body = m.group(1)
        hs = [h.replace('\\"', '"') for h in quoted.findall(body)]
        if not hs and body.strip():
            hs = [h.strip() for h in body.split(",") if h.strip()]
        rows.append((cur, hs))
        cur = None


def c(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


with open(sys.argv[2], "w", encoding="utf-8") as o:
    o.write('/* generated by elements.py */\n#include "elements.h"\n')
    for i, (_, hs) in enumerate(rows):
        o.write("static const char *const h%d[] = {%sNULL};\n" % (i, "".join(c(h) + ", " for h in hs)))
    o.write("const r4_element_def r4_element_defs[] = {\n")
    for i, (eid, _) in enumerate(rows):
        o.write("    {%s, h%d},\n" % (c(eid), i))
    o.write("};\nconst unsigned r4_element_def_count = %d;\n" % len(rows))
