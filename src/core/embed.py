#!/usr/bin/env python3
"""Writes a file as a C byte array: embed.py INPUT OUTPUT SYMBOL."""
import sys

data = open(sys.argv[1], "rb").read()
sym = sys.argv[3]
with open(sys.argv[2], "w") as out:
    out.write("/* generated by embed.py */\n#include <stddef.h>\n")
    out.write("const unsigned char %s[] = {" % sym)
    for i, b in enumerate(data):
        out.write("%s%d," % ("\n" if i % 24 == 0 else "", b))
    out.write("0};\nconst size_t %s_len = %d;\n" % (sym, len(data)))
